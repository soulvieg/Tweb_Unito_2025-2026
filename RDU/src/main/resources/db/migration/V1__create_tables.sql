/*Script to create the db if not exist*/

/*type: 0 for normal user, 1 for admin user*/
CREATE TABLE users
(
    u_id      INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    username  TEXT    NOT NULL,
    password  TEXT    NOT NULL,
    user_type INTEGER NOT NULL
);

CREATE TABLE posts
(
    p_id  INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    u_id  INTEGER REFERENCES users (u_id) NOT NULL,
    title TEXT                            NOT NULL,
    text  TEXT                            NOT NULL
);

CREATE TABLE comments
(
    c_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    p_id INTEGER REFERENCES posts (p_id) NOT NULL,
    u_id INTEGER REFERENCES users (u_id),
    text TEXT                            NOT NULL
);
